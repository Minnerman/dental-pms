import { expect, test } from "@playwright/test";
import { createPatient } from "./helpers/api";
import { ensureAuthReady, getBaseUrl, primePageAuth } from "./helpers/auth";

test("manage reusable prescriptions and customize a patient copy without changing the template", async ({ page, request }, testInfo) => {
  const base = getBaseUrl();
  const token = await ensureAuthReady(request);
  const headers = { Authorization: `Bearer ${token}` };
  const name = `Synthetic usual prescription ${Date.now()}`;
  await primePageAuth(page, request);
  await page.goto(`${base}/templates`);
  await page.getByRole("tab", { name: "Prescriptions", exact: true }).click();
  await expect(page.getByTestId("prescription-template-name")).toBeEnabled();
  await page.getByTestId("prescription-template-name").fill(name);
  await page.getByTestId("prescription-template-medicine").fill("Synthetic medicine - no clinical use");
  await page.getByTestId("prescription-template-directions").fill("Synthetic usual directions");
  await page.getByTestId("prescription-template-quantity").fill("Synthetic quantity");
  const createdResponse = page.waitForResponse((res) => res.url().endsWith("/api/prescription-templates") && res.request().method() === "POST");
  await page.getByTestId("prescription-template-save").click();
  const created = await createdResponse;
  expect(created.status()).toBe(201);
  const savedTemplate = await created.json();
  await expect(page.getByRole("status")).toHaveText("Prescription template saved.");
  await page.reload();
  await page.getByRole("tab", { name: "Prescriptions", exact: true }).click();
  await page.getByTestId("prescription-template-select").selectOption(String(savedTemplate.id));
  await expect(page.getByTestId("prescription-template-directions")).toHaveValue("Synthetic usual directions");
  await page.getByTestId("prescription-template-directions").fill("Revised usual directions");
  await page.getByTestId("prescription-template-save").click();
  await expect(page.getByRole("status")).toHaveText("Prescription template saved.");
  await page.screenshot({ path: testInfo.outputPath("prescription-templates.png"), fullPage: true });

  const patientId = await createPatient(request, { first_name: "Synthetic", last_name: "PrescriptionLibrary" });
  const docs = await (await request.get(`${base}/api/document-templates`, { headers })).json() as { id: number; name: string }[];
  const layout = docs.find((item) => item.name === "Private Prescription - typed")!;
  await page.goto(`${base}/patients/${patientId}/documents`);
  await page.getByTestId("patient-document-template-select").selectOption(String(layout.id));
  const choice = page.getByTestId("prescription-saved-template");
  await choice.selectOption(String(savedTemplate.id));
  await expect(page.getByTestId("prescription-medicine")).toHaveValue(savedTemplate.medicine);
  await expect(page.getByTestId("prescription-directions")).toHaveValue("Revised usual directions");
  await expect(page.getByTestId("prescription-quantity")).toHaveValue(savedTemplate.quantity);
  await page.getByTestId("prescription-prescriber_name").fill("Synthetic Prescriber");
  await page.getByTestId("prescription-prescriber_gdc").fill("TEST-ONLY");
  await page.getByTestId("patient-document-preview").click();
  await expect(page.locator("textarea[readonly]")).toHaveValue(/Revised usual directions/);
  await page.getByTestId("prescription-directions").fill("Patient-specific synthetic directions");
  await expect(page.locator("textarea[readonly]")).toHaveCount(0);
  const saveResponse = page.waitForResponse((res) => res.url().endsWith(`/api/patients/${patientId}/documents`) && res.request().method() === "POST");
  await page.getByTestId("patient-document-save").click();
  const savedResponse = await saveResponse;
  expect(savedResponse.status()).toBe(201);
  const document = await savedResponse.json();
  expect(document.rendered_content).toContain("Patient-specific synthetic directions");
  await expect(choice).toHaveValue("");
  await expect(page.getByTestId("prescription-medicine")).toHaveValue("");

  await page.goto(`${base}/templates?tab=prescriptions`);
  await page.getByTestId("prescription-template-select").selectOption(String(savedTemplate.id));
  await expect(page.getByTestId("prescription-template-directions")).toHaveValue("Revised usual directions");
  await page.getByTestId("prescription-template-active").uncheck();
  await page.getByTestId("prescription-template-save").click();
  await expect(page.getByRole("status")).toHaveText("Prescription template saved.");
  await page.goto(`${base}/patients/${patientId}/documents`);
  const availableResponse = page.waitForResponse((res) => res.url().endsWith("/api/prescription-templates") && res.request().method() === "GET");
  await page.getByTestId("patient-document-template-select").selectOption(String(layout.id));
  expect((await (await availableResponse).json() as { id: number }[]).some((item) => item.id === savedTemplate.id)).toBe(false);
  await expect(choice.locator(`option[value="${savedTemplate.id}"]`)).toHaveCount(0);
  const text = await request.get(`${base}/api/patient-documents/${document.id}/download`, { headers });
  expect(await text.text()).toBe(document.rendered_content);
});
